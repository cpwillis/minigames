// Regenerates shared/profanity-words.ts from the vendored public word list.
// Run: node scripts/build-profanity.mjs   (only needed when the list is updated)
//
// The list says WHAT is profane. This script decides HOW each entry may be matched, because
// substring-matching a 400-entry list against short display names is wildly over-eager:
// "advertisement" contains "semen", "Ashkenazi" contains "nazi", "Swanky" contains "wank".
// An entry earns substring matching only if no innocent English word contains it, tested
// against the system dictionary. Everything else is matched as a whole word or phrase.
import { readFileSync, writeFileSync, existsSync } from 'node:fs'

const LIST = 'shared/ldnoobw-en.txt'
const DICT = '/usr/share/dict/words'
const OUT = 'shared/profanity-words.ts'

// Entries whose only dictionary blockers are archaic ("cushite", "placuntoma") or are themselves
// profane ("whoremonger", "niggerhead"), so the automatic test is too conservative. This can only
// PROMOTE entries that are already in the public list: it never introduces a new word, which the
// test suite asserts.
const FORCE_SUBSTRING = new Set([
  'shit',    // cushite, brushite, girgashite
  'cunt',    // placuntitis, placuntoma
  'nigger',  // niggerdom, niggerfish, niggerhead: all slur derivatives
  'slut',    // coverslut, slutch, sluthood
  'whore',   // whoredom, whoremonger: profane themselves
  'penis',   // micropenis, megalopenis
  'vagina',  // cervicovaginal, extravaginal
])

if (!existsSync(DICT)) {
  console.error(`No dictionary at ${DICT}. Needed to decide which entries are safe as substrings.`)
  process.exit(1)
}

const entries = [...new Set(
  readFileSync(LIST, 'utf8').split('\n').map(w => w.trim().toLowerCase()).filter(Boolean),
)]
// Display names are [a-zA-Z0-9 ] only, so entries with other characters can never match.
const usable = entries.filter(w => /^[a-z0-9 ]+$/.test(w)).sort()
const singles = usable.filter(w => !w.includes(' '))

const dict = readFileSync(DICT, 'utf8').split('\n')
  .map(w => w.trim().toLowerCase())
  .filter(w => w && /^[a-z]+$/.test(w) && w.length <= 20)

const substring = singles.filter(w =>
  FORCE_SUBSTRING.has(w) || (w.length >= 4 && !dict.some(d => d !== w && d.includes(w))),
).sort()

for (const forced of FORCE_SUBSTRING) {
  if (!singles.includes(forced)) throw new Error(`FORCE_SUBSTRING entry "${forced}" is not in the public list`)
}

writeFileSync(OUT, `// GENERATED by scripts/build-profanity.mjs. Do not edit by hand.
//
// Source data: List of Dirty, Naughty, Obscene, and Otherwise Bad Words (English),
// (c) 2012-2020 Shutterstock, Inc. Licensed CC-BY-4.0.
// https://github.com/LDNOOBW/List-of-Dirty-Naughty-Obscene-and-Otherwise-Bad-Words
// See shared/NOTICE.md and shared/ldnoobw-LICENSE.txt.

/** Blocked as a whole word or whole phrase. ${usable.length} entries. */
export const PROFANITY: readonly string[] = ${JSON.stringify(usable, null, 0).replace(/","/g, '", "')}

/** Also blocked when embedded in a longer run of letters. ${substring.length} entries. */
export const PROFANITY_SUBSTRINGS: readonly string[] = ${JSON.stringify(substring, null, 0).replace(/","/g, '", "')}
`)

console.log(`${usable.length} entries (${usable.length - singles.length} phrases), ${substring.length} safe as substrings -> ${OUT}`)
